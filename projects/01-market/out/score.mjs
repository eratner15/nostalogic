// Deterministic mechanics scorecard. Adapted from NostalDamus scoring logic.
// Revision 2 (decision D-008): the window term is a block-level constant, not a per-mechanic input.
// Usage: node projects/01-market/out/score.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const CURRENT_YEAR = 2026;
const PEAK_CHILDHOOD_AGE = 12;
const SWEET_SPOT_CENTER = 40;
const WINDOW_MIDPOINT = 1995; // midpoint of 1993 to 1998

const input = JSON.parse(readFileSync(join(here, "mechanics-input.json"), "utf8"));

function windowAlignment(year) {
  const age = CURRENT_YEAR - year + PEAK_CHILDHOOD_AGE;
  return Math.max(0, Math.round(100 - Math.abs(age - SWEET_SPOT_CENTER) * 8));
}
const BLOCK_WINDOW = windowAlignment(WINDOW_MIDPOINT); // 76, applied once at block level

function scoreOf(sal, rep) {
  return Math.round(sal * 0.5 + rep * 0.5);
}
function riskOf(m) {
  return Math.min(
    100,
    Math.round(
      m.expressionRisk * 0.45 +
        Math.max(0, 80 - m.reproducibility) * 0.25 +
        Math.max(0, m.ownerEffort - 30) * 0.3
    )
  );
}
function band(s, r) {
  if (s >= 85 && r < 45) return "Reproduce";
  if (s >= 75) return "Adapt";
  if (s >= 60) return "Test";
  return "Drop for v1";
}
function score(m) {
  const s = scoreOf(m.memorySalience, m.reproducibility);
  const r = riskOf(m);
  return { ...m, score: s, risk: r, recommendation: band(s, r) };
}

const rows = input.mechanics.map(score).sort((a, b) => b.score - a.score || a.risk - b.risk);
const L = [];
L.push("# Mechanics Scorecard");
L.push("");
L.push(`Generated by score.mjs from mechanics-input.json. Model: scoring-model.md (revision 2, decision D-008). Inputs dated ${input.asOf}.`);
L.push("");
L.push("Formula: score = memorySalience * 0.50 + reproducibility * 0.50.");
L.push(`Block-level window alignment (applied once, not per mechanic): midpoint ${WINDOW_MIDPOINT}, audience age ${CURRENT_YEAR - WINDOW_MIDPOINT + PEAK_CHILDHOOD_AGE}, alignment ${BLOCK_WINDOW} (Sweet Spot).`);
L.push("Risk: expressionRisk * 0.45 + max(0, 80 - reproducibility) * 0.25 + max(0, ownerEffort - 30) * 0.30.");
L.push("Bands: Reproduce if score >= 85 and risk < 45. Adapt if score >= 75. Test if score >= 60. Drop for v1 below 60.");
L.push("");
L.push("| Rank | Mechanic | Salience | Reproducibility | Score | Expr. risk | Effort | Risk | Recommendation |");
L.push("|---|---|---|---|---|---|---|---|---|");
rows.forEach((m, i) => {
  L.push(`| ${i + 1} | ${m.name} | ${m.memorySalience} | ${m.reproducibility} | **${m.score}** | ${m.expressionRisk} | ${m.ownerEffort} | ${m.risk} | ${m.recommendation} |`);
});
L.push("");
L.push("## Reasons per input");
L.push("");
rows.forEach((m, i) => {
  L.push(`### ${i + 1}. ${m.name}`);
  L.push(`- Salience ${m.memorySalience}: ${m.reasons.memorySalience}`);
  L.push(`- Reproducibility ${m.reproducibility}: ${m.reasons.reproducibility}`);
  L.push(`- Expression risk ${m.expressionRisk}: ${m.reasons.expressionRisk}`);
  L.push(`- Owner effort ${m.ownerEffort}: ${m.reasons.ownerEffort}`);
  L.push(`- Arithmetic: ${m.memorySalience} * 0.50 + ${m.reproducibility} * 0.50 = ${m.score}. Risk: ${m.expressionRisk} * 0.45 + ${Math.max(0, 80 - m.reproducibility)} * 0.25 + ${Math.max(0, m.ownerEffort - 30)} * 0.30 = ${m.risk}.`);
  L.push("");
});
L.push("## Sensitivity");
L.push("");
L.push("Each mechanic re-scored with salience 10 points lower and 10 points higher. A recommendation that changes under either shift is marked FLIP.");
L.push("");
L.push("| Mechanic | Base | Salience -10 | Salience +10 | Stable? |");
L.push("|---|---|---|---|---|");
rows.forEach((m) => {
  const lo = band(scoreOf(Math.max(0, m.memorySalience - 10), m.reproducibility), m.risk);
  const hi = band(scoreOf(Math.min(100, m.memorySalience + 10), m.reproducibility), m.risk);
  const stable = lo === m.recommendation && hi === m.recommendation ? "Stable" : "FLIP";
  L.push(`| ${m.name} | ${m.score} ${m.recommendation} | ${scoreOf(Math.max(0, m.memorySalience - 10), m.reproducibility)} ${lo} | ${scoreOf(Math.min(100, m.memorySalience + 10), m.reproducibility)} ${hi} | ${stable} |`);
});
L.push("");
L.push("## Summary");
L.push("");
for (const rec of ["Reproduce", "Adapt", "Test", "Drop for v1"]) {
  const names = rows.filter((m) => m.recommendation === rec).map((m) => m.name);
  L.push(`- ${rec}: ${names.length ? names.join(", ") : "none"}`);
}
L.push("");
L.push("## How the H2 verdict enters the model");
L.push("");
L.push("H2 is WEAKENED: the wrapper raises the floor and hit shows set the ceiling. The model does not score shows. It ranks which wrapper mechanics to keep. The H2 verdict enters as a ceiling on what any mechanic can claim: no mechanic is scored on ratings lift, only on recall (salience) and on whether a small digital studio can run it (reproducibility). The Reproduce band is deliberately narrow so that few mechanics reach it.");
L.push("");
writeFileSync(join(here, "mechanics-scorecard.md"), L.join("\n"));
