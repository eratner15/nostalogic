// Deterministic mechanics scorecard. Adapted from NostalDamus scoring logic.
// Usage: node projects/01-market/out/score.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const CURRENT_YEAR = 2026;
const PEAK_CHILDHOOD_AGE = 12;
const SWEET_SPOT_CENTER = 40;

const input = JSON.parse(readFileSync(join(here, "mechanics-input.json"), "utf8"));

function windowAlignment(peakYear) {
  const age = CURRENT_YEAR - peakYear + PEAK_CHILDHOOD_AGE;
  return Math.max(0, Math.round(100 - Math.abs(age - SWEET_SPOT_CENTER) * 8));
}
function score(m) {
  const wa = windowAlignment(m.peakYear);
  const s = Math.round(m.memorySalience * 0.3 + wa * 0.4 + m.reproducibility * 0.3);
  const r = Math.min(
    100,
    Math.round(
      m.expressionRisk * 0.45 +
        Math.max(0, 80 - m.reproducibility) * 0.25 +
        Math.max(0, m.ownerEffort - 30) * 0.3
    )
  );
  let rec = "Drop for v1";
  if (s >= 88 && r < 45) rec = "Reproduce";
  else if (s >= 78) rec = "Adapt";
  else if (s >= 68) rec = "Test";
  return { ...m, windowAlignment: wa, score: s, risk: r, recommendation: rec };
}

const rows = input.mechanics.map(score).sort((a, b) => b.score - a.score || a.risk - b.risk);
const lines = [];
lines.push("# Mechanics Scorecard");
lines.push("");
lines.push(`Generated by score.mjs from mechanics-input.json. Model: scoring-model.md. Inputs dated ${input.asOf}.`);
lines.push("");
lines.push("Formula: score = memorySalience * 0.30 + windowAlignment * 0.40 + reproducibility * 0.30.");
lines.push("Risk: expressionRisk * 0.45 + max(0, 80 - reproducibility) * 0.25 + max(0, ownerEffort - 30) * 0.30.");
lines.push("");
lines.push("| Rank | Mechanic | Peak year | Window | Salience | Reproducibility | Score | Expr. risk | Effort | Risk | Recommendation |");
lines.push("|---|---|---|---|---|---|---|---|---|---|---|");
rows.forEach((m, i) => {
  lines.push(
    `| ${i + 1} | ${m.name} | ${m.peakYear} | ${m.windowAlignment} | ${m.memorySalience} | ${m.reproducibility} | **${m.score}** | ${m.expressionRisk} | ${m.ownerEffort} | ${m.risk} | ${m.recommendation} |`
  );
});
lines.push("");
lines.push("## Reasons per input");
lines.push("");
rows.forEach((m, i) => {
  lines.push(`### ${i + 1}. ${m.name}`);
  lines.push(`- Peak year ${m.peakYear}: ${m.reasons.peakYear}`);
  lines.push(`- Salience ${m.memorySalience}: ${m.reasons.memorySalience}`);
  lines.push(`- Reproducibility ${m.reproducibility}: ${m.reasons.reproducibility}`);
  lines.push(`- Expression risk ${m.expressionRisk}: ${m.reasons.expressionRisk}`);
  lines.push(`- Owner effort ${m.ownerEffort}: ${m.reasons.ownerEffort}`);
  lines.push(`- Arithmetic: ${m.memorySalience} * 0.30 + ${m.windowAlignment} * 0.40 + ${m.reproducibility} * 0.30 = ${m.score}. Risk: ${m.expressionRisk} * 0.45 + ${Math.max(0, 80 - m.reproducibility)} * 0.25 + ${Math.max(0, m.ownerEffort - 30)} * 0.30 = ${m.risk}.`);
  lines.push("");
});
lines.push("## Summary");
lines.push("");
for (const rec of ["Reproduce", "Adapt", "Test", "Drop for v1"]) {
  const names = rows.filter((m) => m.recommendation === rec).map((m) => m.name);
  lines.push(`- ${rec}: ${names.length ? names.join(", ") : "none"}`);
}
lines.push("");
writeFileSync(join(here, "mechanics-scorecard.md"), lines.join("\n"));
console.log(rows.map((m) => `${m.score}\t${m.risk}\t${m.recommendation}\t${m.name}`).join("\n"));
