// Builds seed/seed.sql and public/posters/*.svg from content/shows.json.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const shows = JSON.parse(readFileSync(join(root, "content/shows.json"), "utf8"));
const q = (v) => (v == null ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const lines = ["-- Generated by scripts/build-seed.mjs from content/shows.json. Do not edit by hand."];
for (const s of shows) {
  lines.push(
    `INSERT OR REPLACE INTO shows (id, slot, title, logline, blurb, genre_label, rating_label, runtime_label, trailer_url, trailer_seconds, poster_hue, status, sort_order) VALUES (${[s.id, s.slot, s.title, s.logline, s.blurb, s.genreLabel, s.ratingLabel ?? "Family", s.runtimeLabel ?? "30 min", s.trailerUrl ?? null, s.trailerSeconds ?? null, s.posterHue ?? 30, s.status ?? "trailer", s.sortOrder ?? 0].map(q).join(", ")});`
  );
}
writeFileSync(join(root, "seed/seed.sql"), lines.join("\n") + "\n");
// Static poster files for the <video poster> attribute.
mkdirSync(join(root, "public/posters"), { recursive: true });
const esc = (t) => t.replace(/[&<>"']/g, (ch) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[ch]);
for (const s of shows) {
  const h = s.posterHue ?? 30;
  const svg = `<svg viewBox="0 0 1280 720" xmlns="http://www.w3.org/2000/svg"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="hsl(${h} 55% 28%)"/><stop offset="1" stop-color="hsl(${(h + 40) % 360} 60% 14%)"/></linearGradient></defs><rect width="1280" height="720" fill="url(#g)"/><circle cx="998" cy="274" r="230" fill="hsl(${(h + 180) % 360} 70% 62% / 0.28)"/><circle cx="1050" cy="245" r="86" fill="hsl(${(h + 180) % 360} 80% 80% / 0.55)"/><rect y="656" width="1280" height="64" fill="hsl(${h} 30% 8% / 0.55)"/><text x="36" y="696" font-family="Barlow Condensed, Impact, sans-serif" font-weight="800" font-size="64" fill="hsl(${h} 20% 96%)">${esc(s.title.toUpperCase())}</text></svg>`;
  writeFileSync(join(root, `public/posters/${s.id}.svg`), svg);
}
console.log(`seed: ${shows.length} shows`);
