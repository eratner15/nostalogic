"""Quantize the trained model to int8 and write the blob the engine loads.

Linear weights and the embedding get one scale per row. Norms and positions stay float32.
Writes:
  build/model_q8.bin                          for the terminal engine and the eval
  firmware/m5dial/src/model_blob.h (--header) for the device; the array lives in flash

Run: python3 hatchling/train/quantize.py --header
"""

import argparse
import os
import struct

import numpy as np
import torch

MAGIC, VERSION = 0x48415443, 2


def pad4(b: bytes) -> bytes:
    return b + b"\0" * (-len(b) % 4)


def q8(w: np.ndarray) -> bytes:
    scale = np.abs(w).max(axis=1) / 127.0
    scale[scale == 0] = 1.0
    q = np.clip(np.round(w / scale[:, None]), -127, 127).astype(np.int8)
    return pad4(scale.astype("<f4").tobytes()) + pad4(q.tobytes())


def f32(w: np.ndarray) -> bytes:
    return pad4(w.astype("<f4").tobytes())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", default="hatchling/build")
    ap.add_argument("--header", action="store_true", help="also write the firmware header")
    ap.add_argument("--header-path", default="hatchling/firmware/m5dial/src/model_blob.h")
    args = ap.parse_args()

    ck = torch.load(os.path.join(args.build, "model.pt"))
    sd = {k: v.float().numpy() for k, v in ck["state"].items()}
    dim, layers, heads, vocab_n, ctx, first_word = ck["cfg"]
    vocab = [w.strip("\n") for w in open(os.path.join(args.build, "vocab.txt"))][:vocab_n]

    vb = pad4(b"".join(w.encode() + b"\0" for w in vocab))
    out = struct.pack("<8i", MAGIC, VERSION, dim, layers, heads, vocab_n, ctx, first_word)
    out += struct.pack("<i", len(vb)) + vb
    out += q8(sd["tok.weight"]) + f32(sd["pos.weight"])
    for i in range(layers):
        p = f"blocks.{i}."
        out += f32(sd[p + "ln1.weight"]) + q8(sd[p + "qkv.weight"]) + q8(sd[p + "proj.weight"])
        out += f32(sd[p + "ln2.weight"]) + q8(sd[p + "fc.weight"]) + q8(sd[p + "out.weight"])
    out += f32(sd["lnf.weight"])

    path = os.path.join(args.build, "model_q8.bin")
    with open(path, "wb") as f:
        f.write(out)
    print(f"wrote {path} ({len(out) / 1e6:.2f} MB)")

    if args.header:
        os.makedirs(os.path.dirname(args.header_path), exist_ok=True)
        with open(args.header_path, "w") as f:
            f.write("/* Generated by train/quantize.py. Do not edit. */\n#pragma once\n#include <stdint.h>\n")
            f.write(f"#define MODEL_BLOB_LEN {len(out)}\n")
            f.write("static const uint8_t MODEL_BLOB[] __attribute__((aligned(4))) = {\n")
            for i in range(0, len(out), 24):
                f.write(",".join(str(b) for b in out[i:i + 24]) + ",\n")
            f.write("};\n")
        print(f"wrote {args.header_path}")


if __name__ == "__main__":
    main()
