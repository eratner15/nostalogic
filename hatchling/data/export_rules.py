"""Write engine/rules.h from data/rules.py so the device uses the same rules.

Regex phrases become plain " phrase " substrings. Alternation groups are expanded.
Run: python3 hatchling/data/export_rules.py
"""

import itertools
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from rules import BANNED_PHRASES, BANNED_WORDS, MAX_WORDS  # noqa: E402

# Fixed, reviewed lines the device shows when every sample fails the filter.
FALLBACK = [
    "Hmm. I am thinking.", "Hello!", "I feel cozy.", "La la la.", "What a day.",
    "I like it here.", "Boop.", "Time for a little rest.",
]


def expand(pattern: str) -> list[str]:
    p = pattern.replace(r"\b", "")
    parts = re.split(r"(\([^)]*\))", p)
    choices = [part[1:-1].split("|") if part.startswith("(") else [part] for part in parts]
    return ["".join(c) for c in itertools.product(*choices)]


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    phrases = sorted({" " + x + " " for p in BANNED_PHRASES for x in expand(p)})
    words = sorted(" " + w + " " for w in BANNED_WORDS)
    out = os.path.join(os.path.dirname(__file__), "..", "engine", "rules.h")
    with open(out, "w") as f:
        f.write("/* Generated by data/export_rules.py. Do not edit. */\n")
        f.write(f"#define MAX_WORDS {MAX_WORDS}\n")
        for name, xs in (("BANNED", words + phrases), ("FALLBACK", FALLBACK)):
            f.write(f"static const char *{name}[] = {{\n")
            for x in xs:
                f.write(f"    {c_str(x)},\n")
            f.write("};\n")
            f.write(f"#define N_{name} (sizeof({name}) / sizeof({name}[0]))\n")
    print(f"wrote {out}: {len(words)} words, {len(phrases)} phrases, {len(FALLBACK)} fallbacks")


if __name__ == "__main__":
    main()
